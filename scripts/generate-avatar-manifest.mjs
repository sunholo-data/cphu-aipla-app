#!/usr/bin/env node
/**
 * generate-avatar-manifest.mjs — the avatar set a teacher can choose from.
 *
 * TUTOR-2 M4. M, 2026-09-28: "we use our own avatars for now and we will upload
 * more so there is more choice." That decision removed the hardest thing in
 * 1.1.135 — a teacher-uploaded image that a 16-year-old sees would have been the
 * first user-generated student-facing content in AIPLA and needed a moderation
 * policy nobody had written.
 *
 * The cost of choosing instead of uploading is that "we will upload more" must
 * not mean a code change each time. So the picker reads this generated manifest:
 * drop a file into frontend/public/personas/, run `make avatars`, done.
 *
 * ⚠️ `make check-avatars` (CI) fails when the manifest and the directory
 * disagree. That half is the one that matters — a dropped-in file nobody
 * regenerated is invisible, which looks exactly like the feature not working.
 *
 * Same generate-and-gate shape as `make sim-prompt` / `make check-sim-prompt`
 * and `make tutor-docs` / `make check-tutor-docs`.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const AVATAR_DIR = join(root, "frontend/public/personas");
const OUT = join(root, "frontend/src/lib/avatarManifest.ts");
// ⚠️ The BACKEND validates against the same list, so "chosen, not uploaded" is
// enforced at the store and not only in the picker — a UI-only rule is one
// fetch away from being bypassed. Two outputs, ONE source of truth: the
// directory listing. A backend allow-list maintained by hand would drift from
// the images the moment someone added one.
const OUT_JSON = join(root, "backend/personas/avatars.json");
const EXTENSIONS = /\.(webp|png|jpg|jpeg|svg)$/i;

/** Title-case a filename for the picker's alt text: "frida.webp" -> "Frida". */
function label(file) {
  return file
    .replace(EXTENSIONS, "")
    .split(/[-_]/)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(" ");
}

const files = readdirSync(AVATAR_DIR).filter((f) => EXTENSIONS.test(f)).sort();
const entries = files.map((f) => ({ path: `/personas/${f}`, label: label(f) }));

const body = `// GENERATED by scripts/generate-avatar-manifest.mjs — do not edit by hand.
// Add an avatar by dropping the image into frontend/public/personas/ and
// running \`make avatars\`. CI (\`make check-avatars\`) fails if the two drift.
//
// The set is CHOSEN from, never uploaded to (TUTOR-2 M4): no user-generated
// student-facing imagery, so no moderation policy is needed.

export interface AvatarChoice {
  /** Public path, exactly as a persona's \`avatar\` field stores it. */
  path: string;
  label: string;
}

export const AVATAR_CHOICES: AvatarChoice[] = ${JSON.stringify(entries, null, 2)};

/** The set the backend validates against, so "chosen, not uploaded" is true at
 *  the store and not only in the UI. */
export const AVATAR_PATHS: string[] = AVATAR_CHOICES.map((a) => a.path);
`;

const json = `${JSON.stringify({ avatars: entries.map((e) => e.path) }, null, 2)}\n`;

const check = process.argv.includes("--check");
if (check) {
  let current = "";
  let currentJson = "";
  try {
    current = readFileSync(OUT, "utf8");
    currentJson = readFileSync(OUT_JSON, "utf8");
  } catch {
    /* missing counts as drift */
  }
  if (current !== body || currentJson !== json) {
    console.error("FAIL: the avatar manifest is out of date.");
    console.error(`  ${files.length} image(s) in frontend/public/personas/`);
    console.error("  Run `make avatars` and commit the result.");
    console.error("");
    console.error("⚠️ An avatar nobody regenerated the manifest for is invisible");
    console.error("   in the picker — which looks like the feature not working.");
    process.exit(1);
  }
  console.log(`OK: avatar manifest matches ${files.length} image(s).`);
} else {
  writeFileSync(OUT, body);
  writeFileSync(OUT_JSON, json);
  console.log(`Wrote the manifest to both sides with ${files.length} avatar(s).`);
}
