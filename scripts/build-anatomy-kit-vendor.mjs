#!/usr/bin/env node
/*
 * build-anatomy-kit-vendor.mjs — the anatomy kit's drawing half as a vendored
 * sim library: /vendor/anatomy-kit/<upstream commit>/iso-kit.js.
 *
 * Source: the vendored skill at .claude/skills/anatomy/ (MIT, pinned commit in
 * its AIPLA.md). Output: one classic script that defines the kit's drawing
 * functions as globals (iso, extrude, cylinder, solidSvg, fitProjection, …) and
 * injects the kit's CSS once, so a sim can draw with the kit without a build
 * step. The page builders and the CSS-as-a-string half are left out, as in the
 * otto-engine build. Generated, never hand-edited: re-run after a re-sync.
 *
 * Usage:
 *   node scripts/build-anatomy-kit-vendor.mjs          # write + print the sha384 for vendor.json
 *   node scripts/build-anatomy-kit-vendor.mjs --check  # CI: the committed file matches the source
 *
 * Why it is not an npm dependency like three.js: upstream is a GitHub repo, not
 * a package. vendored-libraries.md records the exception.
 */
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const REPO = join(dirname(fileURLToPath(import.meta.url)), "..");
const KIT = join(REPO, ".claude", "skills", "anatomy", "kit");
const AIPLA = readFileSync(join(REPO, ".claude", "skills", "anatomy", "AIPLA.md"), "utf8");
const COMMIT = (AIPLA.match(/Pinned commit:\*\*\s*`([0-9a-f]{7,40})`/) || [])[1];
if (!COMMIT) {
  console.error("build-anatomy-kit-vendor: no pinned commit found in .claude/skills/anatomy/AIPLA.md");
  process.exit(2);
}
export const VERSION = COMMIT.slice(0, 7);
export const OUT = join(REPO, "infrastructure", "mcp-sandbox", "vendor-src", "anatomy-kit", VERSION, "iso-kit.js");

function build() {
  const src = readFileSync(join(KIT, "iso-kit.mjs"), "utf8");
  const cut = src.indexOf("function swatchSvg");
  if (cut < 0) throw new Error("iso-kit.mjs has no swatchSvg: the cut point moved upstream");
  const drawing = src.slice(0, cut).replace(/^import .*$/gm, "").replace(/^export /gm, "");
  const css = readFileSync(join(KIT, "iso.css"), "utf8");
  return [
    `/* anatomy kit ${COMMIT} — drawing half + CSS. MIT, github.com/wheresryan22/anatomy.`,
    "   Generated by scripts/build-anatomy-kit-vendor.mjs; do not edit. */",
    drawing.trim(),
    "",
    "(function () {",
    "  if (typeof document === 'undefined' || document.getElementById('anatomy-kit-css')) return;",
    "  var s = document.createElement('style');",
    "  s.id = 'anatomy-kit-css';",
    `  s.textContent = ${JSON.stringify(css)};`,
    "  (document.head || document.documentElement).appendChild(s);",
    "})();",
    "",
  ].join("\n");
}

const body = build();
const sha = createHash("sha384").update(body).digest("base64");
if (process.argv.includes("--check")) {
  if (!existsSync(OUT) || readFileSync(OUT, "utf8") !== body) {
    console.error(`build-anatomy-kit-vendor: ${OUT} is stale. Run: node scripts/build-anatomy-kit-vendor.mjs`);
    process.exit(1);
  }
  console.log(`anatomy-kit ${VERSION} vendored copy is current (sha384-${sha})`);
} else {
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, body);
  console.log(`wrote ${OUT} (${(body.length / 1024).toFixed(1)} KB)\nversion ${VERSION}\nsha384 ${sha}`);
}
